#!/usr/bin/env bash
# Generate a Markdown report describing the full analysis pipeline:
# inputs, per-step method, live tool/reference versions, and outputs.
#
# Usage: make_pipeline_report.sh <outdir> <versions_yaml> <samples_csv> \
#          <trim_min_quality> <trim_min_length> \
#          <enable_cnv> <enable_sv> <enable_repeats> <enable_pgx> <emit_gvcf> \
#          <enable_panel> <panel_name> <out_md>
set -euo pipefail

OUTDIR=$1; VERS=$2; SAMPLES_CSV=$3
TRIM_Q=$4; TRIM_LEN=$5
CNV=$6; SV=$7; REPEATS=$8; PGX=$9; GVCF=${10}
PANEL_ON=${11}; PANEL=${12}; OUT=${13}

on() { [ "$1" = "True" ] || [ "$1" = "true" ]; }
yn() { if on "$1"; then echo "yes"; else echo "no"; fi; }

# ---- sample count (mirror the Snakefile parser: strip # comments / blanks) ----
N_SAMPLES=$(sed 's/#.*//' "$SAMPLES_CSV" | grep -cve '^[[:space:]]*$' || true)

# ---- live tool/reference versions (written by the `versions` rule) ----
vers() { grep -E "^$1:" "$VERS" 2>/dev/null | head -1 | cut -d'"' -f2; }
V_DRAGEN=$(vers dragen); V_ICA=$(vers ica); V_HT=$(vers hashtable_version)
: "${V_DRAGEN:=NA}" "${V_ICA:=NA}" "${V_HT:=NA}"

# ---- per-caller method bullets and output rows ----
STEPS=""; OUTPUTS=""
if on "$GVCF"; then
    STEPS+="   - gVCF emitted alongside the VCF (\`--vc-emit-ref-confidence GVCF\`);"$'\n'
    OUTPUTS+="| \`${OUTDIR}/<sample>/<sample>.hard-filtered.gvcf.gz\` | genome gVCF (for joint genotyping) |"$'\n'
fi
if on "$CNV"; then
    STEPS+="   - copy-number calling with self-normalization (\`--enable-cnv\`);"$'\n'
    OUTPUTS+="| \`${OUTDIR}/<sample>/<sample>.cnv.vcf.gz\` | CNV calls |"$'\n'
fi
if on "$SV"; then
    STEPS+="   - structural-variant calling (\`--enable-sv\`);"$'\n'
    OUTPUTS+="| \`${OUTDIR}/<sample>/<sample>.sv.vcf.gz\` | SV calls |"$'\n'
fi
if on "$REPEATS"; then
    STEPS+="   - repeat-expansion genotyping, ExpansionHunter default catalog (\`--repeat-genotype-enable\`);"$'\n'
    OUTPUTS+="| \`${OUTDIR}/<sample>/<sample>.repeats.vcf.gz\` | repeat-expansion genotypes |"$'\n'
fi
if on "$PGX"; then
    STEPS+="   - targeted callers (CYP2D6, GBA, SMN1/2, ...), star-allele and PGx calling (\`--enable-targeted --enable-star-allele --enable-pgx\`);"$'\n'
    OUTPUTS+="| \`${OUTDIR}/<sample>/<sample>.star_allele*\`, \`*.pgx*\`, \`*.targeted*\` | star alleles / PGx / targeted-gene calls |"$'\n'
fi

PANEL_INTRO=""; PANEL_STAGE=""; PANEL_STEP=""; PANEL_OUT=""; PANEL_YN="no"
if on "$PANEL_ON"; then
    PANEL_YN="$PANEL"
    PANEL_INTRO=" A curated **${PANEL}** gene panel is extracted into a queryable SQLite database (see the separate \`${PANEL}_report\`)."
    PANEL_STAGE="| panel extraction | bcftools / sqlite3 | \`results/${PANEL}_variants.sqlite\` |"$'\n'
    PANEL_STEP="4. **panel extraction** — annotated VCFs subset to the ${PANEL} panel genes, merged,
   site-annotated once with Nirvana (gnomAD / ClinVar / dbSNP / REVEL / phyloP), and
   loaded into SQLite + .xlsx. Detail in the \`${PANEL}_report\`."
    PANEL_OUT="| \`results/${PANEL}_variants.sqlite\` / \`.xlsx\` | queryable ${PANEL}-panel variant DB |"$'\n'
fi

cat > "$OUT" <<EOF
# WGS analysis pipeline report

_Generated by \`src/make_pipeline_report.sh\` — do not edit by hand; re-run the \`pipeline_report\` Snakemake rule._

## 1. Overview

Paired-end whole-genome FASTQs for **${N_SAMPLES} sample(s)** are mapped, deduplicated,
and variant-called genome-wide with the **DRAGEN** germline pipeline. Small-variant
calls are annotated with **Illumina Connected Annotations (Nirvana)** and QC is
aggregated with **MultiQC**.${PANEL_INTRO}

| stage | tool | output |
|---|---|---|
| map / align / call | DRAGEN ${V_DRAGEN} | \`${OUTDIR}/<sample>/\` |
| annotation | Nirvana (ICA ${V_ICA}) | \`${OUTDIR}/<sample>/<sample>.annotated.vcf.gz\` |
| QC aggregation | MultiQC | \`${OUTDIR}/multiqc/multiqc_report.html\` |
${PANEL_STAGE}
## 2. Inputs

| input | value |
|---|---|
| samples | ${N_SAMPLES} (sample sheet \`${SAMPLES_CSV}\`) |
| reference | hg38 pangenome, hashtable v${V_HT} |
| CNV | $(yn "$CNV") |
| SV | $(yn "$SV") |
| repeat expansions | $(yn "$REPEATS") |
| PGx / star alleles | $(yn "$PGX") |
| gVCF | $(yn "$GVCF") |
| gene panel | ${PANEL_YN} |

## 3. Pipeline steps

1. **dragen** — per sample, one DRAGEN run does:
   - adapter + quality trimming (Trimmomatic TruSeq3-PE-2 adapters, min quality
     **${TRIM_Q}**, min length **${TRIM_LEN}**);
   - map / align to the hg38 pangenome, duplicate removal;
   - genome-wide germline SNV / indel calling;
${STEPS}   - genome-wide coverage and mapping QC.
   Runs are serialized (\`resources: dragen=1\`) — one DRAGEN job at a time.
2. **nirvana** — each sample's hard-filtered small-variant VCF annotated with Nirvana
   on GRCh38 (transcript consequences, HGVS, gene symbols) → \`<sample>.annotated.vcf.gz\`.
3. **multiqc** — all DRAGEN QC (trimming, mapping, coverage, ploidy, callers) scanned
   from \`${OUTDIR}\` into one HTML report.
${PANEL_STEP}

## 4. Tool & reference versions

Live-detected at run time by the \`versions\` rule (\`${OUTDIR}/versions.yaml\`).

| component | version |
|---|---|
| DRAGEN | ${V_DRAGEN} |
| Illumina Connected Annotations (Nirvana) | ${V_ICA} |
| hg38 pangenome hashtable | ${V_HT} |

## 5. Key outputs

| path | contents |
|---|---|
| \`${OUTDIR}/<sample>/<sample>.bam\` | mapped, deduplicated reads |
| \`${OUTDIR}/<sample>/<sample>.hard-filtered.vcf.gz\` | DRAGEN small-variant calls |
| \`${OUTDIR}/<sample>/<sample>.annotated.vcf.gz\` | Nirvana-annotated small variants |
${OUTPUTS}| \`${OUTDIR}/multiqc/multiqc_report.html\` | aggregated QC |
| \`${OUTDIR}/versions.yaml\` | provenance (tool / reference versions) |
EOF
printf "%s" "$PANEL_OUT" >> "$OUT"

echo "wrote $OUT"
