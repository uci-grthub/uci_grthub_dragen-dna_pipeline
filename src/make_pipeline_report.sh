#!/usr/bin/env bash
# Generate a Markdown report describing the full analysis pipeline:
# inputs, per-step method, live tool/reference versions, and outputs.
#
# Usage: make_pipeline_report.sh <outdir> <versions_yaml> <samples_csv> \
#          <target_bed> <probe_bed> <target_padding> <with_spike_in> \
#          <trim_min_quality> <trim_min_length> <panel_name> <out_md>
set -euo pipefail

OUTDIR=$1; VERS=$2; SAMPLES_CSV=$3
TARGET_BED=$4; PROBE_BED=$5; PADDING=$6; SPIKE=$7
TRIM_Q=$8; TRIM_LEN=$9; PANEL=${10}; OUT=${11}

# ---- sample count (mirror the Snakefile parser: strip # comments / blanks) ----
N_SAMPLES=$(sed 's/#.*//' "$SAMPLES_CSV" | grep -cve '^[[:space:]]*$' || true)

# ---- live tool/reference versions (written by the `versions` rule) ----
vers() { grep -E "^$1:" "$VERS" 2>/dev/null | head -1 | cut -d'"' -f2; }
V_DRAGEN=$(vers dragen); V_ICA=$(vers ica); V_HT=$(vers hashtable_version)
: "${V_DRAGEN:=NA}" "${V_ICA:=NA}" "${V_HT:=NA}"

SPIKE_NOTE="kit target BED only"
if [ "$SPIKE" = "True" ] || [ "$SPIKE" = "true" ]; then
    SPIKE_NOTE="union of exome-kit + spike-in target BEDs (merged, non-overlapping)"
fi

cat > "$OUT" <<EOF
# Exome analysis pipeline report

_Generated by \`src/make_pipeline_report.sh\` — do not edit by hand; re-run the \`pipeline_report\` Snakemake rule._

## 1. Overview

Paired-end exome FASTQs for **${N_SAMPLES} sample(s)** are mapped, deduplicated, and
variant-called with **DRAGEN**, restricted to the exome capture regions. Calls are
annotated with **Illumina Connected Annotations (Nirvana)**, QC is aggregated with
**MultiQC**, and a curated **${PANEL}** gene panel is extracted into a queryable SQLite
database (see the separate \`${PANEL}_report\`).

| stage | tool | output |
|---|---|---|
| map / align / call | DRAGEN ${V_DRAGEN} | \`${OUTDIR}/<sample>/<sample>.hard-filtered.vcf.gz\` |
| annotation | Nirvana (ICA ${V_ICA}) | \`${OUTDIR}/<sample>/<sample>.annotated.vcf.gz\` |
| QC aggregation | MultiQC | \`${OUTDIR}/multiqc/multiqc_report.html\` |
| panel extraction | bcftools / sqlite3 | \`results/${PANEL}_variants.sqlite\` |

## 2. Inputs

| input | value |
|---|---|
| samples | ${N_SAMPLES} (sample sheet \`${SAMPLES_CSV}\`) |
| reference | hg38 pangenome, hashtable v${V_HT} |
| capture target | ${SPIKE_NOTE} |
| target BED | \`${TARGET_BED}\` |
| probe BED | \`${PROBE_BED}\` |

## 3. Pipeline steps

1. **merge_beds** _(when spike-in enabled)_ — kit + spike-in BEDs concatenated,
   sorted, and \`bedtools merge\`d into a single non-overlapping target / probe union.
2. **dragen** — per sample, one DRAGEN run does:
   - adapter + quality trimming (Trimmomatic TruSeq3-PE-2 adapters, min quality
     **${TRIM_Q}**, min length **${TRIM_LEN}**);
   - map / align to the hg38 pangenome, duplicate removal;
   - germline variant calling restricted to the target BED, padded **±${PADDING} bp**;
   - on-target coverage QC over both the target and probe BEDs.
   Runs are serialized (\`resources: dragen=1\`) — one DRAGEN job at a time.
3. **nirvana** — each sample's hard-filtered VCF annotated with Nirvana on GRCh38
   (transcript consequences, HGVS, gene symbols) → \`<sample>.annotated.vcf.gz\`.
4. **multiqc** — all DRAGEN QC (trimming, mapping, coverage) scanned from
   \`${OUTDIR}\` into one HTML report.
5. **panel extraction** — annotated VCFs subset to the ${PANEL} panel genes, merged,
   site-annotated once with Nirvana (gnomAD / ClinVar / dbSNP / REVEL / phyloP), and
   loaded into SQLite. Detail in the \`${PANEL}_report\`.

## 4. Tool & reference versions

Live-detected at run time by the \`versions\` rule (\`${OUTDIR}/versions.yaml\`).

| component | version |
|---|---|
| DRAGEN | ${V_DRAGEN} |
| Illumina Connected Annotations (Nirvana) | ${V_ICA} |
| hg38 pangenome hashtable | ${V_HT} |

## 5. Key outputs

| path | contents |
|---|---|
| \`${OUTDIR}/<sample>/<sample>.bam\` | mapped, deduplicated reads |
| \`${OUTDIR}/<sample>/<sample>.hard-filtered.vcf.gz\` | DRAGEN variant calls |
| \`${OUTDIR}/<sample>/<sample>.annotated.vcf.gz\` | Nirvana-annotated calls |
| \`${OUTDIR}/multiqc/multiqc_report.html\` | aggregated QC |
| \`${OUTDIR}/versions.yaml\` | provenance (tool / reference versions) |
| \`results/${PANEL}_variants.sqlite\` | queryable ${PANEL}-panel variant DB |
EOF

echo "wrote $OUT"
