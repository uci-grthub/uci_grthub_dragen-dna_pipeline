#!/usr/bin/env python3
"""Dump the panel SQLite DB to a multi-sheet .xlsx.

Sheet 1 is a generated `Overview` (what each sheet is, what each column means,
recommended filters). Then one sheet per table/view, the joined `panel_annotated`
view first (the main deliverable).

Usage: export_panel_xlsx.py DB.sqlite OUT.xlsx
"""
import sqlite3
import sys

from openpyxl import Workbook
from openpyxl.cell import WriteOnlyCell
from openpyxl.styles import Alignment, Font

db_path, xlsx_path = sys.argv[1], sys.argv[2]
panel_name = sys.argv[3] if len(sys.argv) > 3 else "gene"
panel_desc = sys.argv[4] if len(sys.argv) > 4 else ""

con = sqlite3.connect(db_path)
con.row_factory = sqlite3.Row
cur = con.cursor()


def scalar(sql):
    try:
        return cur.execute(sql).fetchone()[0]
    except sqlite3.Error:
        return "n/a"


# Deliverables first, raw tables last; anything new lands after the known names.
SHEET_ORDER = [
    "pathway_hits",
    "panel_gene_cnv",
    "panel_annotated",
    "key_variant_status",
    "key_variant_carriers",
    "panel_genes",
    "panel_key_variants",
    "panel_variants",
    "variant_annotations",
]
objs = sorted(
    (
        r[0]
        for r in cur.execute(
            "SELECT name FROM sqlite_master "
            "WHERE type IN ('table','view') AND name NOT LIKE 'sqlite_%'"
        )
    ),
    key=lambda n: (SHEET_ORDER.index(n) if n in SHEET_ORDER else len(SHEET_ORDER), n),
)

wb = Workbook(write_only=True)

# ---- Overview sheet -------------------------------------------------------
# Rows are (style, text...) where style drives font/wrapping. Kept as data so
# the sheet stays readable in the source and trivially editable.
H1, H2, HDR, TXT = "h1", "h2", "hdr", "txt"

N_KEY = scalar("SELECT count(*) FROM panel_key_variants;")
N_KEY_CALLED = scalar(
    "SELECT count(*) FROM key_variant_status WHERE status = 'called';"
)

overview = [
    (H1, f"{panel_name} gene-panel variant workbook"),
    (TXT, panel_desc),
    (TXT, "Generated by src/export_panel_xlsx.py from results/<panel>_variants.sqlite."),
    (TXT, "Do not edit by hand — re-run the panel_xlsx Snakemake rule."),
    (TXT, ""),
    (H2, "Cohort summary"),
    (TXT, f"Samples: {scalar('SELECT count(DISTINCT sample) FROM panel_variants;')}"),
    (TXT, f"Panel genes with >=1 variant: {scalar('SELECT count(DISTINCT gene_symbol) FROM panel_variants;')}"),
    (TXT, f"Distinct variant sites: {scalar('SELECT count(DISTINCT variant_id) FROM panel_variants;')}"),
    (TXT, f"Carrier consequence rows: {scalar('SELECT count(*) FROM panel_variants;')}"),
    (
        TXT,
        f"A-priori key variants (rsIDs named in the panel): {N_KEY} listed, "
        f"{N_KEY_CALLED} called in this cohort",
    ),
    (TXT, ""),
    (H2, "Sheets"),
    (HDR, "sheet", "grain", "what it is"),
    (
        TXT,
        "panel_annotated",
        "one row per variant x transcript x carrier sample",
        "START HERE. panel_variants + variant_annotations + gene metadata — genotypes, "
        "consequences, annotation and the is_key_variant flag all in one place.",
    ),
    (
        TXT,
        "key_variant_status",
        "one row per a-priori rsID",
        "Did the pipeline call each variant the panel names, and in how many samples "
        "(n_carriers / n_het / n_hom). status = 'not called' means the site is absent from the "
        "cohort VCF — check exome_capture_note before reading anything into that.",
    ),
    (
        TXT,
        "key_variant_carriers",
        "one row per (a-priori rsID x carrier sample)",
        "Who carries each a-priori variant, with genotype, depth and annotation. Redundant "
        "transcript rows already collapsed — this sheet needs no de-duplication.",
    ),
    (
        TXT,
        "panel_genes",
        "one row per panel gene",
        "The curated panel CSV verbatim: category, priority, mechanism, key_variants, "
        "evidence_note, exome_capture_note.",
    ),
    (
        TXT,
        "panel_key_variants",
        "one row per (gene, rsID)",
        "The rsIDs parsed out of the panel's key_variants column — the lookup behind the "
        "is_key_variant flag.",
    ),
    (
        TXT,
        "panel_variants",
        "one row per variant x transcript x carrier sample",
        "Genotype + predicted consequence. Hom-ref and missing genotypes are dropped, so a row "
        "means that sample carries that allele.",
    ),
    (
        TXT,
        "variant_annotations",
        "one row per variant (variant_id)",
        "Sample-independent population / clinical / in-silico annotation. Join key is variant_id "
        "(Nirvana chrom-pos-ref-alt).",
    ),
    (TXT, ""),
    (H2, "The a-priori key-variant flag"),
    (
        TXT,
        "is_key_variant = 1 on panel_annotated means the row's dbSNP rsID exactly matches an rsID "
        "named in the panel's key_variants column. Filter "
        "is_key_variant = 1 to jump straight to the variants the panel was designed around. "
        "Everything else is a 0 — including genuinely interesting variants, so do not treat the "
        "flag as a quality score.",
    ),
    (
        TXT,
        "The flag can only ever match rsIDs. Panel genes whose key variants are described as star "
        "alleles, haplotypes or a variant class (e.g. 'CYP2D6 *4', 'LoF variants', 'GWAS locus', "
        "'risk haplotype') contribute NO rsID and therefore never get flagged. is_key_variant = 0 in "
        "those genes says nothing at all — inspect them by hand.",
    ),
    (TXT, ""),
    (H2, "Read this before filtering"),
    (
        TXT,
        "Each variant appears MULTIPLE times: once per carrier sample, times every transcript it "
        "hits — and both Ensembl (ENST...) and RefSeq (NM_.../NP_...) transcripts are annotated. "
        "Filter feature to start with 'ENST' to drop the duplicate RefSeq rows, otherwise you will "
        "double-count.",
    ),
    (
        TXT,
        "impact and consequence are PREDICTED MOLECULAR effects, not clinical calls. A high-impact "
        "variant is not automatically pathogenic. Triage using clinvar_significance, gnomad_af and "
        "revel together.",
    ),
    (
        TXT,
        "An empty annotation cell means 'not reported in that database', NOT 'benign' / 'absent from "
        "the population'. A variant with no gnomAD row is unobserved there, which is weak evidence "
        "of rarity, not proof.",
    ),
    (
        TXT,
        "Absence of variants in a gene is not evidence of absence: copy-number and structural "
        "alleles (e.g. CYP2D6 star alleles / CNVs) are not represented in this small-variant DB — "
        "see the DRAGEN CNV / SV / star-allele / PGx outputs. WGS does cover promoter / intronic / "
        "regulatory sites. Read exome_capture_note (if the panel supplies one) for gene-specific "
        "caveats.",
    ),
    (TXT, ""),
    (H2, "Column guide + recommended filters"),
    (HDR, "column", "meaning", "recommended filter"),
    (
        TXT,
        "is_key_variant",
        "1 = this row's rsID is one the panel names a priori in key_variants.",
        "is_key_variant = 1 for the hypothesis-driven shortlist. Note a 0 in a star-allele / "
        "haplotype gene is uninformative (see above).",
    ),
    (
        TXT,
        "gene_category / gene_priority",
        "Panel metadata carried over per gene: category and priority tier, as defined in the "
        "panel CSV (empty if the panel does not supply them).",
        "Rank findings by the panel's highest priority tiers first.",
    ),
    (
        TXT,
        "exome_capture_note",
        "Panel-supplied coverage / recoverability caveat for the gene's key variants (for exome-era panels it describes exome capture limits; WGS recovers non-coding sites).",
        "Read it before interpreting any negative result. Genes marked with a warning cannot "
        "produce the variant you are looking for, whatever the filters say.",
    ),
    (
        TXT,
        "gnomad_af",
        "Global allele frequency in gnomAD v4.1 (all populations). Low = rare.",
        "Rare, plausibly-causal: gnomad_af < 0.001. Loose screen: < 0.01. Blank = not in gnomAD "
        "(treat as rare, verify by hand).",
    ),
    (
        TXT,
        "gnomad_hom",
        "Count of homozygous-alt individuals in gnomAD.",
        "gnomad_hom = 0 supports a severe/deleterious allele (no known healthy homozygotes). A high "
        "count argues against a strong effect, whatever the impact says.",
    ),
    (
        TXT,
        "clinvar_significance",
        "Aggregate ClinVar germline classification: Benign ... Pathogenic, or 'Conflicting "
        "classifications of pathogenicity'. Multiple values are ';'-joined.",
        "Flagged: contains 'athogenic' (catches Pathogenic and Likely_pathogenic). Drop noise: "
        "exclude rows that are only Benign / Likely_benign.",
    ),
    (
        TXT,
        "clinvar_review",
        "ClinVar review status = how much to trust the classification.",
        "Trust 'reviewed by expert panel' and 'criteria provided, multiple submitters, no conflicts'. "
        "Discount 'no assertion criteria provided' and single-submitter entries.",
    ),
    (
        TXT,
        "clinvar_conditions",
        "Disease / phenotype terms attached to the ClinVar entry.",
        "Context only — do not filter on it. Check whether the condition is even relevant to the panel's phenotype before "
        "acting on a Pathogenic flag (many are unrelated Mendelian diseases).",
    ),
    (
        TXT,
        "revel",
        "Ensemble missense pathogenicity score, 0-1. Higher = more likely damaging. MISSENSE ONLY — "
        "blank for every other consequence type.",
        "revel > 0.5 suggestive, > 0.7 strong. Useful for missense variants not yet in ClinVar. Never "
        "read a blank revel as benign.",
    ),
    (
        TXT,
        "phylop",
        "Evolutionary conservation at the site. Positive = conserved (under constraint); negative = "
        "fast-evolving.",
        "Supporting evidence only: phylop > 2 marks a conserved site. Do not use alone.",
    ),
    (
        TXT,
        "impact / consequence",
        "Nirvana severity tier (high > moderate > low > modifier) and the Sequence Ontology term "
        "(missense_variant, stop_gained, synonymous_variant, ...).",
        "Coding shortlist: impact IN ('high','moderate'). Predicted loss-of-function: impact = 'high'.",
    ),
    (
        TXT,
        "gt / dp",
        "Genotype (0/1 het, 1/1 hom-alt) and read depth at that site in that sample.",
        "Sanity floor: dp >= 10. Low-depth heterozygous calls are the usual source of false positives — "
        "eyeball the BAM before believing one.",
    ),
    (TXT, ""),
    (H2, "Worked starting point"),
    (
        TXT,
        "The a-priori hypothesis: open key_variant_status (which of the panel's named variants were "
        "called at all), then key_variant_carriers (who carries them). No filtering needed.",
    ),
    (
        TXT,
        "Rare + ClinVar-flagged coding variants: feature starts with 'ENST' AND gnomad_af < 0.01 AND "
        "clinvar_significance contains 'athogenic'.",
    ),
    (
        TXT,
        "Predicted-damaging missense not yet in ClinVar: feature starts with 'ENST' AND revel > 0.7 AND "
        "clinvar_significance is blank.",
    ),
    (
        TXT,
        "Loss-of-function carriers: feature starts with 'ENST' AND impact = 'high', sorted by gnomad_af "
        "ascending.",
    ),
]

ws = wb.create_sheet(title="Overview")
ws.column_dimensions["A"].width = 26
ws.column_dimensions["B"].width = 52
ws.column_dimensions["C"].width = 82

for style, *cells in overview:
    row = []
    for i, text in enumerate(cells):
        cell = WriteOnlyCell(ws, value=text)
        if style == H1:
            cell.font = Font(bold=True, size=14)
        elif style == H2:
            cell.font = Font(bold=True, size=12)
        elif style == HDR:
            cell.font = Font(bold=True)
        # Only the wide prose columns wrap; a single-cell line is left to run.
        if i > 0 or len(cells) > 1:
            cell.alignment = Alignment(vertical="top", wrap_text=True)
        row.append(cell)
    ws.append(row)

# ---- data sheets ----------------------------------------------------------
for name in objs:
    ws = wb.create_sheet(title=name[:31])
    rows = cur.execute(f'SELECT * FROM "{name}"')
    ws.append([c[0] for c in rows.description])  # header
    for row in rows:
        ws.append([row[k] for k in row.keys()])

con.close()
wb.save(xlsx_path)
