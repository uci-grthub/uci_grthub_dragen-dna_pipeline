#!/usr/bin/env bash
# Generate a Markdown report describing the gene-panel variant DB:
# overview + live summary stats + a column dictionary explaining every field.
#
# Usage: make_panel_report.sh <panel_name> <sqlite_db> <nirvana_json> <panel_tsv> <out_md>
set -euo pipefail

PANEL=$1; DB=$2; JSON=$3; TSV=$4; OUT=$5

q() { sqlite3 "$DB" "$1"; }   # scalar/quiet query
qt() { sqlite3 -header -column "$DB" "$1"; }  # table query

# ---- live summary numbers ----
N_GENES=$(grep -vE '^#|^gene_symbol' "$TSV" | grep -cve '^[[:space:]]*$')
N_OBSERVED=$(q "SELECT count(DISTINCT gene_symbol) FROM panel_variants;")
# per-source gene counts, e.g. "GO 87, CPIC 3, GO;CPIC 1, PharmGKB 3"
SRC_BREAKDOWN=$(grep -vE '^#|^gene_symbol' "$TSV" | cut -f2 \
                | sort | uniq -c | sort -rn \
                | awk '{printf "%s%s %s", (NR>1?", ":""), $2, $1}')
N_SAMPLES=$(q "SELECT count(DISTINCT sample) FROM panel_variants;")
N_ROWS=$(q "SELECT count(*) FROM panel_variants;")
N_SITES=$(q "SELECT count(DISTINCT variant_id) FROM panel_variants;")
N_HIGH=$(q "SELECT count(DISTINCT variant_id||sample) FROM panel_variants WHERE impact='high' AND feature LIKE 'ENST%';")
N_ANNOT=$(q "SELECT count(*) FROM variant_annotations;")

# ---- Nirvana data-source versions (from the JSON header) ----
SRC=$(zcat "$JSON" | head -c 20000 \
      | jq -r '.header.dataSources[] | "| \(.name) | \(.version) | \(.releaseDate // "") |"' 2>/dev/null \
      | grep -iE 'gnomAD\b|ClinVar\b|dbSNP|REVEL|phyloP|1000 Genomes Project \|' | sort -u || true)
GENOME=$(zcat "$JSON" | head -c 2000 | jq -r '.header.genomeAssembly' 2>/dev/null || echo GRCh38)
ANNOTATOR=$(zcat "$JSON" | head -c 2000 | jq -r '.header.annotator' 2>/dev/null || echo "Illumina Connected Annotations")

# ---- top genes by carrier rows ----
TOP_GENES=$(qt "SELECT gene_symbol AS gene, count(*) AS rows, count(DISTINCT sample) AS samples
                FROM panel_variants GROUP BY gene_symbol ORDER BY rows DESC LIMIT 10;")

cat > "$OUT" <<EOF
# ${PANEL^} gene-panel variant report

_Generated by \`src/make_panel_report.sh\` — do not edit by hand; re-run the \`panel_report\` Snakemake rule._

## 1. What this is

Variants called across the exome cohort, restricted to a sourced **${PANEL}** gene panel
(**${N_GENES} genes**, listed in \`${TSV}\`), merged across all samples and annotated with
${ANNOTATOR} on **${GENOME}**. The queryable output is a SQLite database,
\`results/${PANEL}_variants.sqlite\`.

The panel is built reproducibly by \`src/fetch_pain_genes.sh\` from two sources, recorded per
gene in the panel's \`source\` column:

- **GO** — pain biology: genes annotated (QuickGO, human Swiss-Prot) to _sensory perception of
  pain_ (GO:0019233), _response to pain_ (GO:0048265), _behavioral response to pain_
  (GO:0048266), and _opioid receptor signaling pathway_ (GO:0038003), including descendants.
- **CPIC / PharmGKB** — pain management pharmacogenomics: analgesic gene-drug pairs from CPIC
  clinical guidelines (e.g. CYP2D6 opioids, CYP2C9 NSAIDs) plus PharmGKB VIP genes.

Source breakdown: ${SRC_BREAKDOWN}.

| metric | value |
|---|---:|
| panel genes | ${N_GENES} |
| panel genes with ≥1 cohort variant | ${N_OBSERVED} |
| samples | ${N_SAMPLES} |
| distinct variant sites (in-panel) | ${N_SITES} |
| carrier consequence rows | ${N_ROWS} |
| annotated variants | ${N_ANNOT} |
| high-impact carrier calls (Ensembl transcripts) | ${N_HIGH} |

## 2. How it was built (pipeline)

1. **panel_bed** — panel gene symbols looked up in the GENCODE v47 GTF → padded, merged
   coordinate BED (\`results/${PANEL}_genes.bed\`, chr-prefixed to match the VCFs).
2. **panel_subset** — each sample's Nirvana-annotated VCF streamed through
   \`bcftools view -T <bed>\` to keep only in-panel records.
3. **panel_merge** — per-sample subsets combined into one multi-sample VCF
   (\`results/${PANEL}_variants.vcf.gz\`).
4. **panel_sites / panel_annotate** — genotypes dropped, then the unique sites annotated
   **once** with Nirvana in JSON mode (gnomAD, ClinVar, dbSNP, REVEL, phyloP).
5. **panel_db** — \`bcftools +split-vep\` flattens per-sample consequences; \`jq\` flattens the
   JSON annotations; both load into SQLite, joined on the variant id.

Only variants whose consequence falls on a **panel gene** are kept; hom-ref and missing
genotypes are dropped (the table lists **carriers only**).

## 3. Database structure

Open with any SQLite viewer, or \`sqlite3 results/${PANEL}_variants.sqlite\`.

| object | grain | purpose |
|---|---|---|
| \`panel_variants\` | one row per (variant × transcript-consequence × carrier sample) | genotypes + consequence annotation |
| \`variant_annotations\` | one row per variant (\`variant_id\`) | population / clinical / in-silico annotation |
| \`panel_annotated\` (view) | \`panel_variants\` LEFT JOIN annotations | **query this** — everything in one place |

Join key is \`variant_id\` — Nirvana's canonical id \`chrom-pos-ref-alt\` (unprefixed, indel-safe),
identical to the CSQ \`VariantId\` in the VCF.

## 4. Column dictionary

### \`panel_variants\` (genotype + consequence)
| column | meaning |
|---|---|
| \`chrom\`, \`pos\`, \`ref\`, \`alt\` | variant locus on ${GENOME} (chr-prefixed) |
| \`sample\` | sample id (DRAGEN RGSM) |
| \`gt\` | genotype — \`0/1\` heterozygous, \`1/1\` homozygous-alt |
| \`dp\` | read depth at the site for that sample (FORMAT/DP) |
| \`gene_symbol\` | gene symbol (Nirvana CSQ) |
| \`gene_ncbi_id\` | NCBI/Entrez gene id |
| \`feature\` | transcript id — \`ENST…\` Ensembl or \`NM_…\`/\`NP_…\` RefSeq (both are annotated) |
| \`canonical\` | \`True\` if the canonical transcript for the gene |
| \`consequence\` | Sequence Ontology term, e.g. \`missense_variant\`, \`stop_gained\`, \`synonymous_variant\` |
| \`impact\` | Nirvana severity tier: \`high\` › \`moderate\` › \`low\` › \`modifier\` |
| \`biotype\` | transcript biotype (\`protein_coding\` / \`mRNA\`, etc.) |
| \`hgvsc\`, \`hgvsp\` | HGVS coding / protein nomenclature (\`.\` when not applicable) |
| \`variant_id\` | join key to \`variant_annotations\` |

### \`variant_annotations\` (population / clinical / in-silico)
| column | source | meaning |
|---|---|---|
| \`variant_id\` | Nirvana | \`chrom-pos-ref-alt\` join key |
| \`rsid\` | dbSNP | dbSNP rs identifier(s) |
| \`gnomad_af\` | gnomAD v4.1 | **global allele frequency** (all populations). Low = rare. \`< 0.001\` is a common rarity cutoff |
| \`gnomad_hom\` | gnomAD v4.1 | count of homozygous-alt individuals in gnomAD (0 → no known healthy homozygotes) |
| \`clinvar_significance\` | ClinVar | aggregate germline classification — \`Benign\` … \`Pathogenic\`, or \`Conflicting classifications of pathogenicity\`. Multiple values \`;\`-joined |
| \`clinvar_review\` | ClinVar | review status / confidence (e.g. _criteria provided, multiple submitters, no conflicts_) |
| \`clinvar_conditions\` | ClinVar | associated disease/phenotype terms |
| \`revel\` | REVEL | missense pathogenicity score, 0–1. Higher = more likely damaging (\`> 0.5\` suggestive, \`> 0.7\` strong). Missense only |
| \`phylop\` | phyloP | evolutionary conservation. Positive = conserved (constraint); negative = fast-evolving |

**Interpretation caveat:** \`impact\`/\`consequence\` describe the predicted molecular effect; they
are **not** clinical calls. Use \`clinvar_significance\`, \`gnomad_af\`, and \`revel\` together to
triage. Rows with \`feature LIKE 'ENST%'\` are Ensembl transcripts (filter to avoid RefSeq
duplicate rows of the same variant).

## 5. Top panel genes by carrier rows

\`\`\`
${TOP_GENES}
\`\`\`

## 6. Example queries

Rare, ClinVar-flagged coding variants:
\`\`\`sql
SELECT gene_symbol, sample, rsid, gnomad_af, clinvar_significance, hgvsp
FROM panel_annotated
WHERE feature LIKE 'ENST%'
  AND gnomad_af < 0.01
  AND clinvar_significance LIKE '%athogenic%';
\`\`\`

High-impact (LoF) carriers:
\`\`\`sql
SELECT gene_symbol, sample, gt, consequence, hgvsp, gnomad_af
FROM panel_annotated
WHERE impact = 'high' AND feature LIKE 'ENST%'
ORDER BY gnomad_af;
\`\`\`

Predicted-damaging missense (REVEL) not yet in ClinVar:
\`\`\`sql
SELECT gene_symbol, sample, hgvsp, revel, gnomad_af
FROM panel_annotated
WHERE revel > 0.7 AND (clinvar_significance = '' OR clinvar_significance IS NULL)
  AND feature LIKE 'ENST%'
ORDER BY revel DESC;
\`\`\`
EOF

echo "wrote $OUT"
